const { generateContent } = require("../../config/geminiClient");
const { safeParseAiJson } = require("../../utils/aiJsonParser");
const {
  SHEET_PARSER_PROMPT_VERSION,
  buildSheetScanParts,
  buildCategorizePrompt,
} = require("../../prompts/sheetParser.prompt");
const { inferProblemCategory } = require("../../utils/dsaCategorizer");

/**
 * Scan a document, image, or raw text using Gemini API
 */
async function scanSheetWithGemini({
  fileBase64,
  mimeType = "application/pdf",
  fileName = "",
  rawText = "",
  apiKey = null,
}) {
  const parts = buildSheetScanParts({ fileBase64, mimeType, fileName, rawText });

  const result = await generateContent({
    contents: [{ parts }],
    temperature: 0.2,
    responseMimeType: "application/json",
    timeout: 60000,
    customApiKey: apiKey,
  });

  if (!result?.text) {
    throw new Error("No output generated by Gemini for sheet scan.");
  }

  try {
    const parsed = safeParseAiJson(result.text);
    const items = Array.isArray(parsed) ? parsed : (parsed?.problems || parsed?.items || []);

    return items.map((item) => ({
      number: item.number ? String(item.number).trim() : null,
      title: item.title ? String(item.title).trim() : "Untitled Problem",
      platform: item.platform ? String(item.platform).trim() : null,
      questionUrl: item.questionUrl && String(item.questionUrl).startsWith("http") ? String(item.questionUrl).trim() : null,
      solutionUrl: item.solutionUrl && String(item.solutionUrl).startsWith("http") ? String(item.solutionUrl).trim() : null,
      url: item.url && String(item.url).startsWith("http") ? String(item.url).trim() : null,
      difficulty: item.difficulty || null,
      topic: item.topic || null,
    }));
  } catch (parseErr) {
    throw new Error(`Failed to parse Gemini sheet scan output: ${parseErr.message}`);
  }
}

/**
 * Intelligently classify a list of problems into structured curriculum modules using Gemini
 */
async function categorizeProblemsWithGemini(problems = [], apiKey = null) {
  if (!Array.isArray(problems) || problems.length === 0) return problems;

  const activeKey = apiKey || process.env.GEMINI_API_KEY;
  if (!activeKey || activeKey === "your_gemini_api_key_here") {
    return problems.map((p) => ({
      ...p,
      module: inferProblemCategory(p.title, p.module || p.topic),
      topic: inferProblemCategory(p.title, p.module || p.topic),
    }));
  }

  const needCategorization = [];
  const result = problems.map((p, idx) => {
    const rawMod = String(p.module || p.topic || "").trim();
    const isGeneric =
      !rawMod ||
      [
        "dsa",
        "core dsa",
        "custom sheet",
        "dsa patterns",
        "general",
        "official problems",
        "custom-1",
        "custom problem",
        "problems",
      ].includes(rawMod.toLowerCase());

    if (isGeneric) {
      needCategorization.push({ originalIndex: idx, id: p.id || idx + 1, title: p.title });
    }
    return { ...p, module: rawMod || "Arrays & Hashing", topic: rawMod || "Arrays & Hashing" };
  });

  if (needCategorization.length === 0) {
    return result;
  }

  const BATCH_SIZE = 50;
  for (let i = 0; i < needCategorization.length; i += BATCH_SIZE) {
    const batch = needCategorization.slice(i, i + BATCH_SIZE);
    const promptText = buildCategorizePrompt(batch);

    const classifiedMap = new Map();
    try {
      const res = await generateContent({
        contents: [{ parts: [{ text: promptText }] }],
        temperature: 0.1,
        responseMimeType: "application/json",
        timeout: 45000,
        customApiKey: apiKey,
      });

      if (res?.text) {
        const parsed = safeParseAiJson(res.text);
        const items = Array.isArray(parsed) ? parsed : parsed?.items || parsed?.problems || [];
        items.forEach((item) => {
          if (item.id != null && item.module) {
            classifiedMap.set(String(item.id), String(item.module).trim());
          }
        });
      }
    } catch (err) {
      console.warn("[SheetParser:categorize] Batch classification warning:", err.message);
    }

    batch.forEach((b) => {
      const assigned = classifiedMap.get(String(b.id)) || inferProblemCategory(b.title);
      result[b.originalIndex].module = assigned;
      result[b.originalIndex].topic = assigned;
    });
  }

  return result;
}

module.exports = {
  scanSheetWithGemini,
  categorizeProblemsWithGemini,
  SHEET_PARSER_PROMPT_VERSION,
};
